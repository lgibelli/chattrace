#!/usr/bin/env python3
"""Regenerate the crate sections of THIRD_PARTY_NOTICES.md and THIRD_PARTY_LICENSES.txt.

Walks the normal (non-dev, non-build) dependency closure of the shipped
binaries for all platforms, using `cargo metadata`. Run from the repo root:

    python3 scripts/gen_notices.py
"""
import glob, json, os, subprocess, sys

ROOTS = {"chattrace"}
MARK = "<!-- crates:begin -->"

meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"]))
pkgs = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
todo = [i for i, p in pkgs.items() if p["name"] in ROOTS and p["source"] is None]
seen = set()
while todo:
    i = todo.pop()
    if i in seen:
        continue
    seen.add(i)
    for d in nodes[i]["deps"]:
        if any(k["kind"] is None for k in d["dep_kinds"]):
            todo.append(d["pkg"])

crates = sorted((pkgs[i] for i in seen if pkgs[i]["source"] is not None), key=lambda p: (p["name"].lower(), p["version"]))

rows = ["| Crate | Version | License | Source |", "|---|---|---|---|"]
for p in crates:
    lic = (p.get("license") or ("see " + p["license_file"] if p.get("license_file") else "unknown")).replace("|", "/")
    src = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}"
    rows.append(f"| {p['name']} | {p['version']} | {lic} | {src} |")

path = "THIRD_PARTY_NOTICES.md"
head = open(path, encoding="utf-8").read().split(MARK)[0]
body = (
    f"{MARK}\n\n## Rust crates linked into the binaries ({len(crates)})\n\n"
    "Generated by `scripts/gen_notices.py` from `cargo metadata` (all target platforms; "
    "a given build links a subset). Full license texts: `THIRD_PARTY_LICENSES.txt`.\n\n"
    + "\n".join(rows) + "\n"
)
open(path, "w", encoding="utf-8").write(head + body)

out = ["ChatTrace Forensic third-party license texts", "=" * 44, ""]
# Assets bundled in the binaries (not crates)
for title, f in [("Inter font (Regular, SemiBold)  —  OFL-1.1", "assets/fonts/Inter-LICENSE.txt"),
                 ("Phosphor Icons font  —  MIT", "assets/fonts/Phosphor-LICENSE.txt")]:
    out += ["-" * 78, title, "-" * 78, open(f, encoding="utf-8").read().rstrip() + "\n"]
missing = []
for p in crates:
    d = os.path.dirname(p["manifest_path"])
    files = sorted(f for pat in ("LICEN[CS]E*", "COPYING*", "NOTICE*", "UNLICENSE*", "fonts/*.txt") for f in glob.glob(os.path.join(d, pat)) if os.path.isfile(f))
    out.append("-" * 78)
    out.append(f"{p['name']} {p['version']}  —  {p.get('license') or ''}")
    out.append("-" * 78)
    if not files:
        missing.append(p["name"])
        authors = ", ".join(p.get("authors") or []) or "the crate authors"
        out.append(f"The published crate ships no license file. License: {p.get('license')}. "
                   f"Copyright (c) {authors}. Canonical license texts are at the end of this file.\n")
    for f in files:
        out.append(f"[{os.path.basename(f)}]")
        out.append(open(f, encoding="utf-8", errors="replace").read().rstrip() + "\n")
def first(pattern):
    for p in crates:
        for f in glob.glob(os.path.join(os.path.dirname(p["manifest_path"]), pattern)):
            return open(f, encoding="utf-8", errors="replace").read().rstrip()
    return ""

out += ["=" * 78, "Canonical license texts", "=" * 78, "", "[Apache License 2.0]", first("LICENSE-APACHE*"), "",
        "[MIT License]", "Permission is hereby granted, free of charge, to any person obtaining a copy of this software and "
        "associated documentation files (the \"Software\"), to deal in the Software without restriction, including without "
        "limitation the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the "
        "Software, and to permit persons to whom the Software is furnished to do so, subject to the following conditions:\n\n"
        "The above copyright notice and this permission notice shall be included in all copies or substantial portions of "
        "the Software.\n\nTHE SOFTWARE IS PROVIDED \"AS IS\", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT "
        "NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT "
        "SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF "
        "CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN "
        "THE SOFTWARE.", ""]
open("THIRD_PARTY_LICENSES.txt", "w", encoding="utf-8").write("\n".join(out))
print(f"{len(crates)} crates; {len(missing)} without license files: {', '.join(missing)}", file=sys.stderr)
